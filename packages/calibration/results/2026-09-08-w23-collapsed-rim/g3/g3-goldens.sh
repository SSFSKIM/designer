#!/bin/bash
# W23 G3 — the goldens re-recorded under an attribution (X2, stop S4).
#
# Three phases, in order, and the order is the evidence's:
#
#   (1) THE ATTRIBUTION, before anything is re-recorded. `g3-golden-attribution.spec.ts` renders
#       every scene twice through the isolation proof's own profile seam — once with the rim's five
#       constants set back to what they were before this gate, once as shipped — and reports the
#       largest 8-bit delta inside the contour band against the largest outside it. A pixel moved
#       outside any band is stop S4.
#   (2) THE SUITE AS IT STANDS, so the failures name themselves: every golden the rim moves fails
#       on its PNG and on its pinned hash, and the hashes the run prints are what goes into
#       W23_HASHES.
#   (3) THE RE-RECORD: `goldens:regen` writes the PNGs, and the isolation hashes are hand-recorded
#       from (2) — that table is never regenerated by a script, which is the point of it.
#
# The attribution spec is copied into the suite for the length of one run and removed after.
set -u
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WORKTREE="$(cd "$HERE/../../../../.." && pwd)"
OUT="$HERE/goldens-attribution.txt"
SPEC="$WORKTREE/packages/renderer-webgpu/e2e/golden/w23-g3-attribution.spec.ts"
cd "$WORKTREE/packages/renderer-webgpu"
{
  echo "W23 G1 — the landed rim law's reach on every golden, and the suite before the re-record"
  echo
  echo "=============================================================================="
  echo "(1) THE ATTRIBUTION — where the rim law's delta lands, per scene"
  echo "=============================================================================="
  cp "$HERE/g3-golden-attribution.spec.ts" "$SPEC"
  npx playwright test w23-g3-attribution --reporter=line 2>&1
  rm -f "$SPEC"
  echo
  echo "=============================================================================="
  echo "(2) THE SUITE BEFORE THE RE-RECORD — every golden the rim moves, with its hash"
  echo "=============================================================================="
  npx playwright test --grep @golden --reporter=line 2>&1
} > "$OUT" 2>&1
echo "-> $OUT"
