"""W42 G0 instrument, finding I-4, the readers: the reader outputs committed in 7efe4ce8 and 9c1623b4 are
regenerated by the code of the commit that committed them, in the scratch roots i4_replay.py describes, with only
the blur store's key changed to a never-reused token, and diffed numerically against the committed JSON.

Usage:
  python3.12 i4_readers.py run ROOT COMMIT OUTPUT CMD...   run CMD in ROOT's instrument folder (W42_POOL as set),
                                                           then diff OUTPUT (and its section files) against COMMIT
  python3.12 i4_readers.py diff ROOT COMMIT OUTPUT...      diff only
Each diff is appended to /tmp/w42fix/i4-out/readers.json: per file, the number of numeric leaves, how many differ
by more than 1e-9 (relative), the largest absolute difference and where, and any structural difference.
"""
import json
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REL = 'packages/calibration/results/2026-09-29-w42-g0-declaration/instrument'
SCRATCH = '/tmp/w42fix'
LOG = f'{SCRATCH}/i4-out/readers.json'


def committed(commit, name):
    out = subprocess.run(['git', '-C', HERE, 'show', f'{commit}:{REL}/{name}'], capture_output=True, check=True)
    return json.loads(out.stdout)


def walk(a, b, path, acc):
    if isinstance(a, dict) and isinstance(b, dict):
        if set(a) != set(b):
            acc['structure'].append(f'{path}: keys {sorted(set(a) ^ set(b))[:6]}')
        for k in set(a) & set(b):
            walk(a[k], b[k], f'{path}.{k}', acc)
    elif isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            acc['structure'].append(f'{path}: length {len(a)} != {len(b)}')
        for i, (x, y) in enumerate(zip(a, b)):
            walk(x, y, f'{path}[{i}]', acc)
    elif isinstance(a, bool) or isinstance(b, bool) or a is None or b is None or isinstance(a, str) or isinstance(b, str):
        if a != b:
            acc['other'].append(f'{path}: {str(a)[:60]!r} != {str(b)[:60]!r}')
    elif isinstance(a, (int, float)) and isinstance(b, (int, float)):
        acc['n'] += 1
        fa, fb = float(a), float(b)
        if fa != fa and fb != fb:
            return
        d = abs(fa - fb)
        if not (d <= 1e-9 * max(1.0, abs(fa), abs(fb))):
            acc['differ'] += 1
            if d > acc['max']:
                acc['max'], acc['where'] = d, f'{path}: {fa!r} -> {fb!r}'
    else:
        acc['other'].append(f'{path}: type {type(a).__name__} != {type(b).__name__}')


def diff(root, commit, name):
    rec = committed(commit, name)
    got = json.load(open(os.path.join(SCRATCH, f'i4-{root}', REL, name)))
    acc = dict(n=0, differ=0, max=0.0, where=None, structure=[], other=[])
    walk(rec, got, '', acc)
    acc['other'] = acc['other'][:12]
    acc['structure'] = acc['structure'][:12]
    return dict(file=name, commit=commit, root=root, **acc)


def append(rows):
    old = json.load(open(LOG)) if os.path.exists(LOG) else []
    json.dump(old + rows, open(LOG, 'w'), indent=1, default=float)


if __name__ == '__main__':
    cmd, root, commit = sys.argv[1:4]
    rest = sys.argv[4:]
    if cmd == 'run':
        sep = rest.index('--')
        outputs, command = rest[:sep], rest[sep + 1:]
        t0 = time.time()
        wd = os.path.join(SCRATCH, f'i4-{root}', REL)
        subprocess.run(command, cwd=wd, check=True)
        rows = [dict(diff(root, commit, o), seconds=time.time() - t0, command=' '.join(command)) for o in outputs]
    else:
        rows = [diff(root, commit, o) for o in rest]
    for r in rows:
        print(f"{r['file']}: {r['n']} numbers, {r['differ']} differ (max {r['max']:.3g} at {r['where']}); "
              f"structure {r['structure'][:2]} other {r['other'][:2]}", flush=True)
    append(rows)
