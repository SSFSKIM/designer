class Worktree:
    """The disposable worktree, and the record of every file a run writes into it."""

    def __init__(self, repo: Path, commit: str, path: Path, keep: bool):
        self.repo, self.commit, self.path, self.keep = repo, commit, path, keep
        self.overwritten: set[str] = set()
        self.created: set[str] = set()
        self.pristine = ""

    def create(self) -> None:
        log(f"worktree {self.path} at {self.commit[:12]}")
        subprocess.run(["git", "worktree", "add", "--detach", str(self.path), self.commit],
                       cwd=self.repo, check=True, capture_output=True)
        result = subprocess.run(["pnpm", "install", "--frozen-lockfile"], cwd=self.path,
                                capture_output=True, text=True)
        (self.path.parent / "pnpm-install.log").write_text(result.stdout + result.stderr)
        if result.returncode != 0:
            raise SystemExit(f"pnpm install --frozen-lockfile failed; see {self.path.parent}/pnpm-install.log")
        self.pristine = git("status", "--porcelain", cwd=self.path)

    def write(self, rel: str, data: bytes) -> None:
        target = self.path / rel
        if target.exists():
            if rel not in self.created:
                self.overwritten.add(rel)
        else:
            self.created.add(rel)
        target.write_bytes(data)

    def restore(self) -> None:
        if self.overwritten:
            subprocess.run(["git", "checkout", self.commit, "--", *sorted(self.overwritten)],
                           cwd=self.path, check=True, capture_output=True)
        for rel in self.created:
            (self.path / rel).unlink(missing_ok=True)
        self.overwritten, self.created = set(), set()
        status = git("status", "--porcelain", cwd=self.path)
        if status != self.pristine:
            raise SystemExit(f"worktree not restored:\n{status}")

    def remove(self) -> None:
        if self.keep:
            log(f"kept {self.path}")
            return
        subprocess.run(["git", "worktree", "remove", "--force", str(self.path)], cwd=self.repo,
                       capture_output=True)
        if self.path.exists():
            shutil.rmtree(self.path, ignore_errors=True)
        subprocess.run(["git", "worktree", "prune"], cwd=self.repo, capture_output=True)


def shipped_documents(wt: Path) -> dict[str, dict]:
    """Every document a current row names, by basename: the files a candidate may replace."""
    sys.path.insert(0, str(wt / CAL_REL / "results/2026-09-26-w40-g0-generations"))
    import matrix_store  # noqa: PLC0415
    rows = matrix_store.load_current_rows(matrix_path=str(wt / CAL_REL / "results/matrix.json"))
    named = {(path, sha) for row in rows for _, path, sha in matrix_store.documents(row)}
    sys.path.pop(0)
    out = {}
    for path, sha in sorted(named):
        name = PurePosixPath(path).name
        data = (wt / path).read_bytes() if (wt / path).exists() else None
        if path != f"{PROFILES_REL}/{name}" or data is None or sha256(data)[:12] != sha:
            continue  # a retired document a current row still names is not "shipped"
        out[name] = dict(path=path, sha12=sha, bytes=data)
    return out


def inspect_test(source: str) -> dict:
    """The fixed cut paths the committed test reads, and whether it carries M2's derivation."""
    paths = []
    for match in re.finditer(r"resolve\(\s*PACKAGE_ROOT\s*,((?:\s*\"[^\"]*\"\s*,?)+)\s*\)", source):
        parts = re.findall(r"\"([^\"]*)\"", match.group(1))
        paths.append("/".join(parts))
    fixed = {}
    for name in ("chroma-cut.json", "exterior-cut.json"):
        hits = sorted({p for p in paths if p.endswith("/" + name)})
        if len(hits) != 1:
            raise Refusal(f"the test at the commit reads {len(hits)} fixed {name} paths: {hits}")
        fixed[name] = f"{CAL_REL}/{hits[0]}"
    for variable in ("VITREA_MATRIX_PATH", "VITREA_WEB_CAPTURES", "VITREA_L1_CUT", "VITREA_X1_CUT"):
        if f'process.env["{variable}"]' not in source:
            raise Refusal(f"the test at the commit does not read {variable}")
    other = sorted({p for p in paths if re.search(r"cut[^/]*\.json$", p)} -
                   {h.removeprefix(CAL_REL + "/") for h in fixed.values()})
    missed_row = re.search(r"interface MissedRow \{(.*?)\n\}", source, re.S)
    m2 = bool(missed_row and re.search(r"readonly native\?: number;", missed_row.group(1))
              and "chromaStructureNamedMisses" in source and source.count(MISSED_ANCHOR) == 1)
    return dict(fixedCuts=fixed, otherCommittedCutsReadAsCommitted=other, m2NamedMissDerivation=m2)


class Run:
    """One side of the comparison: its stages, candidate documents and capture roots."""

    def __init__(self, name: str, stages, candidates, captures, out: Path):
        self.name, self.out = name, out / name
        self.stages = [Path(s).resolve() for s in stages]
        self.candidates = [Path(c).resolve() for c in (candidates or [])]
        self.captures = [Path(c).resolve() for c in captures]
        self.installs: dict[str, bytes] = {}
        self.capture_map: dict[str, str] = {}
        self.relocated_stages: list[Path] = []
        self.record: dict = dict(stages=[], candidates=[])

    def prepare(self, shipped: dict[str, dict]) -> None:
        """Match candidates to declared documents; write the relocated stage copies."""
        self.out.mkdir(parents=True)
        by_sha = {}
        for path in self.candidates:
            data = path.read_bytes()
            if path.name not in shipped:
                raise Refusal(f"{path}: {path.name} is not a shipped document's basename "
                              f"({sorted(shipped)})")
            json.loads(data)
            sha12 = sha256(data)[:12]
            if sha12 in by_sha and by_sha[sha12][1] != data:
                raise Refusal(f"two candidates share sha256:{sha12}")
            by_sha[sha12] = (path, data)
            self.record["candidates"].append(dict(path=str(path), basename=path.name,
                                                  sha256=sha256(data), sha12=sha12,
                                                  bytes=len(data)))
        used = set()
        for index, stage in enumerate(self.stages):
            membership_raw = (stage / "membership.json").read_bytes()
            matrix_raw = (stage / "matrix.json").read_bytes()
            membership = json.loads(membership_raw)
            relocations: dict[tuple[str, str], str] = {}
            for role in ("active", "receded"):
                document = membership.get(role)
                if document is None:
                    continue
                path, sha = document["path"], document["sha256"]
                name = PurePosixPath(path).name
                if name not in shipped:
                    raise Refusal(f"{stage}: {role} {path} is not a shipped document's basename")
                canonical = f"{PROFILES_REL}/{name}"
                if path == canonical and sha == shipped[name]["sha12"]:
                    continue
                if sha not in by_sha:
                    raise Refusal(f"{stage}: {role} {path} sha256:{sha} is neither the shipped "
                                  "document nor a --candidate; pass its bytes with --candidate")
                source_path, data = by_sha[sha]
                if source_path.name != name:
                    raise Refusal(f"{stage}: {role} {path} is a {name}; --candidate {source_path} "
                                  "has that hash under another basename")
                if name in self.installs and self.installs[name] != data:
                    raise Refusal(f"two different candidates would install {name}")
                self.installs[name] = data
                used.add(sha)
                if path != canonical:
                    relocations[(path, sha)] = canonical
                    document["path"] = canonical
            text = matrix_raw.decode()

            def relocate(match: re.Match) -> str:
                target = relocations.get((match.group(2), match.group(3)))
                return match.group(0) if target is None else \
                    f"{match.group(1)}={target} sha256:{match.group(3)}"
            moved = DOCUMENT.sub(relocate, text)
            for path, _ in relocations:
                if path in moved:
                    raise Refusal(f"{stage}: {path} survives relocation outside a document clause")
            before, after = json.loads(text)["cells"], json.loads(moved)["cells"]
            if len(before) != len(after):
                raise Refusal(f"{stage}: relocation changed the row count")
            for old, new in zip(before, after):
                expected = copy.deepcopy(old)
                expected["key"]["web"]["capturePath"] = DOCUMENT.sub(
                    relocate, old["key"]["web"]["capturePath"])
                if new != expected:
                    raise Refusal(f"{stage}: relocation moved more than a document clause")
                self.capture_map[new["key"]["web"]["capturePath"]] = old["key"]["web"]["capturePath"]
            target = self.out / "stages" / f"{index}-{stage.name}"
            target.mkdir(parents=True)
            (target / "membership.json").write_text(json.dumps(membership, indent=2) + "\n")
            (target / "matrix.json").write_text(moved)
            self.relocated_stages.append(target)
            self.record["stages"].append(dict(
                stage=str(stage), membershipSha256=sha256(membership_raw),
                matrixSha256=sha256(matrix_raw), rows=len(before),
                relocatedMatrixSha256=file_sha(target / "matrix.json"),
                relocated={f"{p} sha256:{h}": t for (p, h), t in relocations.items()}))
        unused = [c for c in self.record["candidates"] if c["sha12"] not in used]
        if unused:
            raise Refusal(f"--candidate(s) no stage declares: {[c['path'] for c in unused]}")


def side_path(name: str, sha12: str) -> str:
    return f"{PROFILES_REL}/{name.removesuffix('.json')}.kept-{sha12}.json"


def run_python(args: list[str], cwd: Path, stdout: Path, stderr: Path) -> int:
    env = {k: v for k, v in os.environ.items() if not k.startswith("VITREA_")}
    env.update(OPENBLAS_NUM_THREADS="1", VECLIB_MAXIMUM_THREADS="1", PYTHONDONTWRITEBYTECODE="1")
    with stdout.open("w") as out, stderr.open("w") as err:
        return subprocess.run([sys.executable, "-B", *args], cwd=cwd, stdout=out, stderr=err,
                              env=env).returncode


