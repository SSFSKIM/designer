#!/usr/bin/env python3.12
"""W42 G0 — the owner test on a candidate's scratch union, against its base (charter clause 10).

Clause 10's owner-test bar: "no failure that the base's own scratch union at the same
membership does not show". `adopted-thresholds.test.ts` gates only rows whose documents are
the files in `profiles/`, and it reads committed cuts, so it cannot be pointed at a candidate
rendered at scratch documents; its bytes may not move for this (clause 12). This runs it
UNMODIFIED, twice — once on the base's stages, once on the candidate's — as the seal would
see each, and reports every failure the candidate shows that the base does not.

Per run, inside one disposable detached worktree at `--commit` (default this branch's HEAD):

  1. Each declared candidate document is installed as `packages/calibration/profiles/<basename>`,
     the file it replaces at the seal. A basename no current row names is refused.
  2. Each stage is copied with every document clause naming a candidate's scratch path
     RELOCATED to `profiles/<basename>`, hash unchanged (membership.json and matrix.json).
  3. The scratch union: the current union with every (profile, tier) pair the stages hold
     replaced by their rows, composed from W41 G2's own `referee_source._stage` per stage (one
     stage per scheme, no overlap, every declared non-holdout cell of a held pair present).
     A current row the stages do NOT replace — the CSS tier, a pair not rendered — was drawn at
     the document a candidate now overwrites; it is relocated to a side copy of that document's
     committed bytes, `profiles/<stem>.kept-<sha12>.json`, so it stays gated at what drew it and
     reads identically in both runs. A held pair's holdout cell the stage holds no row for (a
     G2 stage renders none before the exposure) is carried at its current row the same way;
     without that, every count-first case of a held profile fails in both runs and its
     per-cell bounds go unread (--no-carry-holdout restores W41's rule, for evidence). Written
     as one schema-5 legacy envelope.
  4. A capture tree for X1: per cell, the stage's capture (its `cell__webgpu.json` capturePath
     relocated as the row is) or the canonical tree's. Copied, not linked: `w35_readers`
     refuses a payload whose resolved path leaves its root.
  5. The four cuts the test reads, regenerated by the port with its row source replaced by
     that union: chroma and exterior written over their fixed paths in the worktree, L1 and X1
     through VITREA_L1_CUT / VITREA_X1_CUT. M2's reference is the generation current at the
     commit (W32 Decision Log 4).
  6. (default on) M2 named misses as the seal would record them (Decision Log 5a): inserted into
     the worktree's copy of MISSED_27_ROWS, each line logged, only when the test at the commit
     carries the named-miss derivation, which then checks every insertion itself.
  7. `vitest run test/adopted-thresholds.test.ts --reporter=json` with VITREA_MATRIX_PATH,
     VITREA_WEB_CAPTURES, VITREA_L1_CUT and VITREA_X1_CUT set.
  8. (default on; --no-closures for evidence) CLOSURES, the parent's ruling of 2026-09-30: a
     named miss that stops missing is a pass, and its list shrinks at the seal, because floors
     come off by fix. The test compares two named-miss lists with the lists it derives, in both
     directions: MISSED_27_ROWS ("names every 27 row the refit missed") and L1's `MISSES` ("the
     two named, unfloored misses"). So a closing entry fails it exactly as a new miss would, and
     vitest's truncated message cannot tell the two apart. Before each of those two assertions
     the worktree's copy logs the derived and the recorded list to a scratch file (one added
     line each; no assertion changes). Every recorded entry the run no longer derives is a
     closure. The copy then drops the closing entries, as the seal would: the MISSED_27_ROWS
     line is deleted, and `MISSES` is filtered at its assertion. The test runs again, and that
     second run is the run's result. A closure never excuses a new miss: the shrunken list
     still fails on any entry derived and not recorded.

Then the comparison: exit 0 only when no candidate case fails that the base passes, and no case
failing in both fails with a different message. Closures are reported per run and never block.
Exit 1 otherwise; exit 2 on a refusal.

    python3.12 -B run-owner.py --stage LIGHT --stage DARK --candidate DOC ... --captures ROOT \\
        --base-stage BLIGHT --base-stage BDARK --base-captures ROOT --out /tmp/owner-run
"""
