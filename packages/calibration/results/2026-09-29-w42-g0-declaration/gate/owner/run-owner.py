def internal_union(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="run-owner.py _union")
    parser.add_argument("--referees", required=True)
    parser.add_argument("--stage", type=Path, action="append", required=True)
    parser.add_argument("--side", type=Path, required=True,
                        help="JSON: {'<path> <sha12>': '<side path>'} for replaced documents")
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--carry-holdout", action="store_true")
    args = parser.parse_args(argv)
    rs = _import_referees(args.referees)
    store = rs.store
    alive: list = []  # the store keys raw bytes by id(); every row read stays referenced
    staged, replaced, declared, statuses = [], set(), set(), []
    for stage in args.stage:
        membership = json.loads((stage / "membership.json").read_text())
        profiles = set(membership["profiles"])
        if profiles & declared:
            raise SystemExit(f"{stage}: declares {sorted(profiles & declared)}, already declared "
                             "by another stage (one stage per scheme)")
        declared |= profiles
        source = rs._stage(stage.resolve(), False)  # the port's own checks, per stage
        alive.append(source.rows)
        pairs = {(e["profile"], e["renderer"]) for e in source.stage["replaced"]}
        if pairs & replaced:
            raise SystemExit(f"{stage}: replaces {sorted(pairs & replaced)} a prior stage holds")
        replaced |= pairs
        staged += [row for row in source.rows if rs._pair(row) in pairs]
        statuses.append(source.stage)
    side = json.loads(args.side.read_text())
    current = store.load_current_rows(matrix_path=str(rs.RESULTS / "matrix.json"))
    alive.append(current)
    def member(row):
        return (row["key"]["profileKey"], row["key"]["web"]["renderer"], row.get("fixtureSet"),
                row["key"]["sceneId"])
    held = {member(row) for row in staged}
    kept, relocated, carried = [], [], []
    for row in current:
        if rs._pair(row) in replaced:
            # A held pair's holdout cell the stage has no row for: carried at its current row,
            # which both runs then read identically (see main's --no-carry-holdout).
            if not (args.carry_holdout and row.get("fixtureSet") == rs.HOLDOUT
                    and member(row) not in held):
                continue
            carried.append(row)
        hits = [(kind, path, sha) for kind, path, sha in store.documents(row)
                if f"{path} {sha}" in side]
        if not hits:
            kept.append(row)
            continue
        raw = store._RAW[id(row)]
        capture = row["key"]["web"]["capturePath"]
        for kind, path, sha in hits:
            old, new = f"{kind}={path} sha256:{sha}", f"{kind}={side[f'{path} {sha}']} sha256:{sha}"
            if raw.count(old.encode()) != 1 or capture.count(old) != 1:
                raise SystemExit(f"{rs._pair(row)} {row['key']['sceneId']}: clause not unique")
            raw, capture = raw.replace(old.encode(), new.encode()), capture.replace(old, new)
        moved = json.loads(raw)
        expected = copy.deepcopy(row)
        expected["key"]["web"]["capturePath"] = capture
        if moved != expected:
            raise SystemExit(f"{row['key']['sceneId']}: relocation moved more than the clause")
        store._RAW[id(moved)] = raw
        alive.append(moved)
        kept.append(moved)
        relocated.append(dict(profile=row["key"]["profileKey"], renderer=row["key"]["web"]["renderer"],
                              set=row.get("fixtureSet"), scene=row["key"]["sceneId"],
                              capturePath=capture, originalCapturePath=row["key"]["web"]["capturePath"]))
    union = sorted(kept + staged, key=store.key)
    if len({store.key(r) for r in union}) != len(union):
        raise SystemExit("a staged key collides with a kept row")
    body = (b'{\n  "schemaVersion": 5,\n  "cells": [\n    ' +
            b",\n    ".join(store._RAW[id(r)] for r in union) + b"\n  ]\n}\n")
    digest = store.legacy_envelope_digest(union)
    if sha256(body) != digest:
        raise SystemExit("union envelope bytes differ from the legacy digest")
    with args.out.open("xb") as f:
        f.write(body)

    def counted(rows):
        out: dict[str, int] = {}
        for r in rows:
            label = " ".join(rs._pair(r))
            out[label] = out.get(label, 0) + 1
        return dict(sorted(out.items()))
    report = dict(
        rows=len(union), legacyEnvelopeSha256=digest,
        replacedPairs=sorted(" ".join(p) for p in replaced),
        stagedMembers=sorted([r["key"]["profileKey"], r["key"]["web"]["renderer"], r.get("fixtureSet"),
                              r["key"]["sceneId"]] for r in staged),
        stagedRowsByPair=counted(staged),
        keptRowsByPair=counted(r for r in kept if r["key"]["profileKey"].startswith("apple-macos-27.0-")),
        keptRelocatedByPair={},
        holdoutCarriedByPair=counted(carried),
        keptRelocated=relocated,
        sideDocumentsUsed=sorted({side[f"{p} {h}"] for e in relocated
                                  for _, p, h in DOCUMENT.findall(e["originalCapturePath"])
                                  if f"{p} {h}" in side}),
        source=dict(stages=statuses, holdoutCarried=bool(args.carry_holdout),
                    composedBy="run-owner.py _union: referee_source._stage per stage, kept rows "
                               "at a replaced document relocated to its side copy"
                               + ("; a held pair's absent holdout rows carried at their current "
                                  "rows" if args.carry_holdout else "")),
    )
    for e in relocated:
        label = f"{e['profile']} {e['renderer']}"
        report["keptRelocatedByPair"][label] = report["keptRelocatedByPair"].get(label, 0) + 1
    args.report.write_text(json.dumps(report, indent=1) + "\n")
    print(f"union: {len(union)} rows, sha256 {digest}; {len(relocated)} kept rows relocated, "
          f"{len(carried)} holdout rows carried")
    return 0


def internal_cut(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="run-owner.py _cut")
    parser.add_argument("--referees", required=True)
    parser.add_argument("--union", required=True)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--script", required=True)
    parser.add_argument("rest", nargs=argparse.REMAINDER)
    args = parser.parse_args(argv)
    rs = _import_referees(args.referees)
    rows = rs.store.load_current_rows(matrix_path=args.union)
    status = dict(unionFile=args.union, **json.loads(args.report.read_text())["source"])
    source = rs.Source(list(rows), f"scratch union {args.union} (run-owner.py)", status)
    # The port reads its rows through `referee_source.load`; everything after that is its own.
    rs.load = lambda _args: source
    import runpy  # noqa: PLC0415
    script = str(Path(args.referees) / args.script)
    sys.argv = [script] + [a for a in args.rest if a != "--"]
    runpy.run_path(script, run_name="__main__")
    return 0


