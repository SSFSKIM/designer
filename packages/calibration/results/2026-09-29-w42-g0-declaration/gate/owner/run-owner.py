class Refusal(SystemExit):
    """An input the runner will not read; exit 2 with the reason."""

    def __init__(self, message: str):
        print(f"run-owner: REFUSED: {message}", file=sys.stderr)
        super().__init__(2)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def file_sha(path: Path) -> str:
    return sha256(Path(path).read_bytes())


def git(*args: str, cwd: Path, check: bool = True) -> str:
    return subprocess.run(["git", *args], cwd=cwd, check=check, capture_output=True,
                          text=True).stdout.strip()


def log(message: str) -> None:
    print(f"[run-owner {datetime.datetime.now():%H:%M:%S}] {message}", file=sys.stderr, flush=True)


