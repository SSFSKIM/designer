/**
 * W31 G2 — the committed reading of the WGSL range scan (claims §5.163 §1).
 *
 * Writes `call-sites.txt` and `call-sites.json`: every call of a transcendental
 * in `packages/renderer-webgpu/src/wgsl/`, its resolved argument intervals, the
 * verdict, and which of them stand on a written proof rather than on the source.
 *
 * It also re-runs the scan over two MUTATED copies of the shaders, because a
 * table of green rows says nothing about whether the instrument can go red:
 *
 *   - `angle_delta` without this gate's floor — the defect W31 G2 found and
 *     fixed, which must read UNBOUNDED;
 *   - `outer_shadow_falloff` without W30 G3b's ±20 — the defect §5.159b fixed,
 *     which must read UNBOUNDED at the very site whose NaN left a 44 px surface
 *     with a strip undrawn.
 *
 * Run: node --experimental-strip-types scan-report.mjs
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import {
  describeInterval,
  scanSource,
  scanWgslDirectory,
  verdictFor,
  WGSL_DIR,
} from "../../../renderer-webgpu/test/wgsl-range/scan.ts";
import { RANGE_PROOFS } from "../../../renderer-webgpu/test/wgsl-range/proofs.ts";

const HERE = dirname(fileURLToPath(import.meta.url));

const proofFor = (site, argument) =>
  RANGE_PROOFS.find(
    (proof) => proof.file === site.file && proof.call === site.call && proof.argument === argument,
  );

const sites = scanWgslDirectory();
const rows = sites.map((site) => {
  const verdict = verdictFor(site.fn, site.ranges);
  const proofs = verdict.finite
    ? []
    : verdict.unbounded.map((argument) => ({ argument, proof: proofFor(site, argument) }));
  return {
    file: site.file,
    line: site.line,
    fn: site.fn,
    call: site.call,
    arguments: site.args.map((text, index) => ({
      index,
      text,
      range: describeInterval(site.ranges[index]),
    })),
    classification: verdict.finite
      ? "clamped — bounded by the source"
      : proofs.every((entry) => entry.proof !== undefined)
        ? "proven — bounded by a committed range proof"
        : "STOPPED — neither",
    why: verdict.why,
    proofs: proofs.map((entry) => ({
      argument: entry.argument,
      bound: entry.proof?.bound ?? null,
      dependsOn: entry.proof?.dependsOn ?? null,
    })),
  };
});

// The two mutations, each applied to the one file that carries the site.
const read = (name) => readFileSync(join(WGSL_DIR, name), "utf8");
const mutations = [
  {
    label: "angle_delta without W31 G2's floor (highlight.ts)",
    file: "highlight.ts",
    from: "return max(min(raw, TAU - raw), 0.0);",
    to: "return min(raw, TAU - raw);",
    expect: "pow(angle_delta(theta, centre) / width, 2.0)",
  },
  {
    label: "outer_shadow_falloff without W30 G3b's ±20 (optics.ts)",
    file: "optics.ts",
    from: "let t = clamp(0.7978845608028654 * (x + 0.044715 * x * x * x), -20.0, 20.0);",
    to: "let t = 0.7978845608028654 * (x + 0.044715 * x * x * x);",
    expect: "tanh(t)",
  },
];

const mutationRows = mutations.map((mutation) => {
  const source = read(mutation.file);
  if (!source.includes(mutation.from)) {
    throw new Error(`scan-report: the text to mutate is not in ${mutation.file}: ${mutation.from}`);
  }
  const mutated = scanSource(mutation.file, source.replace(mutation.from, mutation.to));
  const site = mutated.find((candidate) => candidate.call === mutation.expect);
  if (site === undefined) throw new Error(`scan-report: no ${mutation.expect} after mutation`);
  const verdict = verdictFor(site.fn, site.ranges);
  return {
    label: mutation.label,
    call: site.call,
    range: describeInterval(site.ranges[0]),
    verdict: verdict.finite ? "BOUNDED — the mutation did NOT expose it" : "UNBOUNDED",
    why: verdict.why,
  };
});

const clamped = rows.filter((row) => row.classification.startsWith("clamped")).length;
const proven = rows.filter((row) => row.classification.startsWith("proven")).length;
const stopped = rows.filter((row) => row.classification.startsWith("STOPPED")).length;

const files = readdirSync(WGSL_DIR).filter((name) => name.endsWith(".ts")).sort();
const withCalls = new Set(rows.map((row) => row.file));

const lines = [
  "W31 G2 — every transcendental call in packages/renderer-webgpu/src/wgsl/, classified.",
  "Generated by scan-report.mjs; claims c9a §5.163 §1.",
  "",
  `${rows.length} call sites over ${files.length} files: ${clamped} clamped by the source, ` +
    `${proven} bounded by a committed proof, ${stopped} STOPPED.`,
  "",
  "Files with no call of exp/exp2/pow/tanh/sinh/cosh/log/log2/inverseSqrt at all:",
  `  ${files.filter((name) => !withCalls.has(name)).join(", ")}`,
  "",
];
for (const row of rows) {
  lines.push(`${row.file}:${row.line}  ${row.fn}  — ${row.classification}`);
  lines.push(`  ${row.call}`);
  for (const argument of row.arguments) {
    lines.push(`  arg${argument.index}: ${argument.text}`);
    lines.push(`          ${argument.range}`);
  }
  lines.push(`  ${row.why}`);
  for (const proof of row.proofs) {
    lines.push(`  proof arg${proof.argument}: ${proof.bound}`);
    for (const dependency of proof.dependsOn ?? []) lines.push(`    depends on ${dependency}`);
  }
  lines.push("");
}
lines.push("The instrument can go red — two mutations, each re-introducing a defect a gate fixed:");
for (const row of mutationRows) {
  lines.push(`  ${row.label}`);
  lines.push(`    ${row.call} -> ${row.range}`);
  lines.push(`    ${row.verdict}`);
  lines.push(`    ${row.why}`);
}
lines.push("");

writeFileSync(join(HERE, "call-sites.txt"), lines.join("\n"));
writeFileSync(
  join(HERE, "call-sites.json"),
  `${JSON.stringify({ rows, mutations: mutationRows, counts: { clamped, proven, stopped } }, null, 2)}\n`,
);
process.stdout.write(lines.join("\n"));
