"""Synthetic-only closure exercise of every join and the actual corrected consumer.

Run under the parent's source collector. All records/images used below are generated by
these bounded fixtures in disposable directories; no production binding or root is opened.
This probe creates no completion instrument, real output inventory or permission record.
"""
import io
from pathlib import Path
import types
import unittest

HERE=Path(__file__).resolve().parent
suite=unittest.TestSuite()
for filename in ('test_assembler.py','test_bound.py','test_validator.py'):
    path=HERE/filename
    module=types.ModuleType('completion_probe_'+path.stem);module.__file__=str(path)
    exec(compile(path.read_bytes(),str(path),'exec',dont_inherit=True),module.__dict__)
    suite.addTests(unittest.defaultTestLoader.loadTestsFromModule(module))
stream=io.StringIO()
result=unittest.TextTestRunner(stream=stream,verbosity=0).run(suite)
if not result.wasSuccessful():
    raise ValueError('Synthetic completion exercise failed: '+stream.getvalue())
