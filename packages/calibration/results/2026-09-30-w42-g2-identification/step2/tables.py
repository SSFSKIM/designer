"""W42 G2 step 2: the markdown tables the ledger and README quote, generated from the fits (no pixel read).

    python3.12 -B tables.py [TAG]     -> tables.md
"""
import json
import sys

import common as C

TAG = sys.argv[1] if len(sys.argv) > 1 else 'main'
FITS = C.HERE / 'fits' / TAG
ORDER = ('LT', 'LT-2k', 'free-sn', 'R1', 'W-shape', 'W-canvas', 'W-tails', 'K2', 'C-linear', 'edge-swap',
         'LT+bleed-lit-pre', 'LT+bleed-lit-post', 'LT+bleed-lit-own-pre', 'LT+bleed-lit-own-post', 'LT+bleed',
         'LT+bleed-own', 'null-texel', 'null-dev', 'null-mix', 'null-R2', 'null-boxfloor')
SHORT = {'k': 'k', 'k_n': 'kₙ', 'k_w': 'k_w', 'mu': 'μ', 's2': 's2', 'a': 'a', 'sk': 'sk', 'k_b': 'k_b'}


def fmt_params(v, ep):
    ps = []
    def key(item):
        n = item[0].split('@')[0]
        return (1, int(n.split('_')[-1])) if n.startswith('sn_') else (0, 0)
    for k, x in sorted(v['params'].items(), key=key):
        name = k.split('@')[0]
        if name.startswith('sn_'):
            name = 'σn' + name.split('_')[-1]
        ps.append(f"{SHORT.get(name, name)} {x:.3f}")
    ps.append(f"λ {v['lam'][ep]:.3f}")
    return ', '.join(ps)


def main():
    L = [f'Generated by tables.py from fits/{TAG}. Worst = largest measured region-statistic miss (codes) over '
         'calibration and validation; fails = failing statistics (measured beyond max(1, bar) or a rail '
         'deficit); pooled = per-cell rms over the calibration cells (codes, reported, never gated).', '']
    for ep in C.EPS:
        L += [f'### {ep} ({C.EP_NAME[ep]})', '',
              '| family | n | least squares: parameters | worst | fails | minimax: parameters | worst | fails | pooled (LS) |',
              '| --- | --- | --- | --- | --- | --- | --- | --- | --- |']
        for fam in ORDER:
            p = FITS / f'{fam}__{ep}__n.json'
            if not p.exists():
                continue
            r = json.loads(p.read_text())
            ls, mm = r['ls'], r['minimax']
            w = lambda v: max(v['calibration']['worstMeasured'], v['validation']['worstMeasured'])
            L.append(f"| {fam}{' (survives)' if r['survives'] else ''} | {r['count']} | {fmt_params(ls, ep)} | "
                     f"{w(ls):.2f} | {ls['failures']} | {fmt_params(mm, ep)} | {w(mm):.2f} | {mm['failures']} | "
                     f"{ls['calibration']['pooledRms']:.2f} |")
        p = FITS / f'LT__{ep}__w.json'
        if p.exists():
            r = json.loads(p.read_text())
            ls, mm = r['ls'], r['minimax']
            w = lambda v: max(v['calibration']['worstMeasured'], v['validation']['worstMeasured'])
            L.append(f"| LT, 53.6-pt mask ({r['cells']['fit']} cells) | 2 | {fmt_params(ls, ep)} | {w(ls):.2f} | "
                     f"{ls['failures']} | {fmt_params(mm, ep)} | {w(mm):.2f} | {mm['failures']} | "
                     f"{ls['calibration']['pooledRms']:.2f} |")
        L.append('')
    for level in ('k@global', 'k@scheme'):
        p = FITS / f'LT@{level}__all__n.json'
        if not p.exists():
            continue
        r = json.loads(p.read_text())
        L += [f'### LT at {level}', '', '| point | k | λ by endpoint | worst / fails by endpoint |', '| --- | --- | --- | --- |']
        for pt in ('ls', 'minimax'):
            v = r[pt]
            L.append(f"| {pt} | {', '.join(f'{k} {x:.3f}' for k, x in v['params'].items())} | "
                     f"{', '.join(f'{e} {x:.3f}' for e, x in v['lam'].items())} | " +
                     ', '.join(f"{e} {max(v['endpoints'][e]['calibration']['worstMeasured'], v['endpoints'][e]['validation']['worstMeasured']):.2f} / {v['endpoints'][e]['failures']}"
                               for e in C.EPS) + ' |')
        L.append('')
    (C.HERE / 'tables.md').write_text('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
